export type SyllabusChoice = 'jamb' | 'waec' | 'both';

export const SYLLABUS_LABEL: Record<SyllabusChoice, string> = {
  jamb: 'JAMB syllabus',
  waec: 'WAEC/NECO syllabus',
  both: 'JAMB + WAEC/NECO (merged)',
};

/** The WAEC/NECO topics for a subject (empty when none are listed). */
export const waecTopics = (subject: string) => WAEC_SYLLABUS[subject] ?? [];

/** The topic list an exam uses: JAMB's, WAEC/NECO's, or both (without repeats). */
export function syllabusTopics(subject: string, choice: SyllabusChoice): string[] {
  if (choice === 'jamb') return jambTopics(subject);
  if (choice === 'waec') return waecTopics(subject);
  const seen = new Set<string>();
  return [...jambTopics(subject), ...waecTopics(subject)].filter((t) => {
    const k = t.toLowerCase();
    if (seen.has(k)) return false;
    seen.add(k);
    return true;
  });
}
